/// <reference types="bun-types" />
import { readFileSync, writeFileSync } from 'node:fs'

import Ajv2020 from 'ajv/dist/2020'
import { _ } from 'ajv/dist/compile/codegen'
import standaloneCode from 'ajv/dist/standalone'

import schemas from './src/wire-schema.json'

const ajv = new Ajv2020({
  strict: false,
  allErrors: false,
  inlineRefs: false,
  code: {
    source: true,
    lines: true,
    formats: _`{
      double: {validate: Number.isFinite},
      uint16: {validate: n => Number.isInteger(n) && n >= 0 && n <= 65535},
      uint32: {validate: n => Number.isInteger(n) && n >= 0 && n <= 4294967295},
      uint64: {validate: n => Number.isSafeInteger(n) && n >= 0}
    }`,
  },
})
ajv.addFormat('double', { type: 'number', validate: Number.isFinite })
ajv.addFormat('uint16', {
  type: 'number',
  validate: n => Number.isInteger(n) && n >= 0 && n <= 65535,
})
ajv.addFormat('uint32', {
  type: 'number',
  validate: n => Number.isInteger(n) && n >= 0 && n <= 4294967295,
})
ajv.addFormat('uint64', {
  type: 'number',
  validate: n => Number.isSafeInteger(n) && n >= 0,
})
const exports: Record<string, string> = {}
for (const key of [
  'request',
  'response',
  'resourceOperation',
  'resourceResponse',
  'storageAction',
  'storageReport',
] as const) {
  ajv.addSchema(schemas[key], key)
  exports[`validate${key[0]!.toUpperCase()}${key.slice(1)}`] = key
}
const header =
  '// Generated by generate-validators.ts from Rust wire-schema.json; do not edit.\n'
const source = header + standaloneCode(ajv, exports).trimEnd() + '\n'
const declarations =
  header +
  "import type { Request, Response, ResourceOperation, ResourceResponse, StorageAction, StorageReport } from './bindings'\n" +
  [
    'Request',
    'Response',
    'ResourceOperation',
    'ResourceResponse',
    'StorageAction',
    'StorageReport',
  ]
    .map(
      type =>
        `export function validate${type}(value: unknown): value is ${type}\n`
    )
    .join('')
const args = process.argv.slice(2)
if (args.length > 1 || (args.length === 1 && args[0] !== '--check'))
  throw new Error('Expected only --check')
for (const [name, expected] of [
  ['wire-validators.cjs', source],
  ['wire-validators.d.cts', declarations],
] as const) {
  const path = new URL(`src/${name}`, import.meta.url)
  if (args[0] === '--check') {
    if (readFileSync(path, 'utf8') !== expected)
      throw new Error(`Generated ${name} is stale; run generate:validators`)
  } else writeFileSync(path, expected)
}
