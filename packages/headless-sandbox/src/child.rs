//! Fixed test child. This binary has no production discovery/launch entry point.
use std::io::{Read, Write};

#[cfg(all(windows, target_arch = "x86_64"))]
extern "C" {
    fn flowtools_p22_evaluate(
        source: *const u8,
        source_len: usize,
        output: *mut u8,
        output_limit: usize,
        output_len: *mut usize,
    ) -> i32;
}

fn main() {
    #[cfg(not(all(windows, target_arch = "x86_64")))]
    {
        eprintln!("UNSUPPORTED_PLATFORM");
        std::process::exit(64);
    }
    #[cfg(all(windows, target_arch = "x86_64"))]
    {
        use windows_sys::Win32::System::{
            Diagnostics::Debug::{
                GetErrorMode, SetErrorMode, SEM_FAILCRITICALERRORS, SEM_NOGPFAULTERRORBOX,
                SEM_NOOPENFILEERRORBOX,
            },
            ErrorReporting::{WerSetFlags, WER_FAULT_REPORTING_NO_UI},
        };
        let inherited_error_mode = unsafe { GetErrorMode() };
        unsafe {
            SetErrorMode(
                inherited_error_mode
                    | SEM_FAILCRITICALERRORS
                    | SEM_NOGPFAULTERRORBOX
                    | SEM_NOOPENFILEERRORBOX,
            );
            if WerSetFlags(WER_FAULT_REPORTING_NO_UI) < 0 {
                windows_sys::Win32::System::Threading::ExitProcess(66);
            }
        }
        let mode = std::env::args().nth(1).unwrap_or_default();
        let mut input = Vec::new();
        if std::io::stdin()
            .take((flowtools_headless_sandbox::INPUT_LIMIT + 1) as u64)
            .read_to_end(&mut input)
            .is_err()
            || input.len() > flowtools_headless_sandbox::INPUT_LIMIT
        {
            std::process::exit(65);
        }
        let value = match serde_json::from_slice::<serde_json::Value>(&input) {
            Ok(value) => value,
            Err(_) => std::process::exit(65),
        };
        let result = match mode.as_str() {
            "--js" => evaluate(&value),
            // Native probes are deliberately compiled into this standalone
            // fixture binary only. They test the OS independently of JS APIs.
            "--native-probe" => probe(&value, inherited_error_mode),
            _ => std::process::exit(64),
        };
        if let Ok(bytes) = serde_json::to_vec(&result) {
            let _ = std::io::stdout().write_all(&bytes);
        }
    }
}

#[cfg(all(windows, target_arch = "x86_64"))]
fn evaluate(request: &serde_json::Value) -> serde_json::Value {
    let Some(source) = request.get("source").and_then(serde_json::Value::as_str) else {
        return serde_json::json!({"error":"INPUT_INVALID"});
    };
    let Some(input) = request.get("input") else {
        return serde_json::json!({"error":"INPUT_INVALID"});
    };
    if request.as_object().map(|value| value.len()) != Some(2) {
        return serde_json::json!({"error":"INPUT_INVALID"});
    }
    // JSON is generated by serde, never interpolated as executable input.
    let input_json = serde_json::to_string(input).unwrap();
    let input_literal = serde_json::to_string(&input_json).unwrap();
    if source.contains('\0') {
        return serde_json::json!({"error":"INPUT_INVALID"});
    }
    let mut program =
        format!("(function(input){{\"use strict\";\n{source}\n}})(JSON.parse({input_literal}))")
            .into_bytes();
    let program_len = program.len();
    // JS_Eval requires input[input_len] to be readable and NUL terminated.
    program.push(0);
    let mut output = vec![0; flowtools_headless_sandbox::OUTPUT_LIMIT - 64];
    let mut size = 0;
    let code = unsafe {
        flowtools_p22_evaluate(
            program.as_ptr(),
            program_len,
            output.as_mut_ptr(),
            output.len(),
            &mut size,
        )
    };
    match code {
        0 => match serde_json::from_slice::<serde_json::Value>(&output[..size]) {
            Ok(value) => serde_json::json!({"value":value}),
            Err(_) => serde_json::json!({"error":"RESULT_INVALID"}),
        },
        3 => serde_json::json!({"error":"DEADLINE"}),
        4 => serde_json::json!({"error":"OUTPUT_LIMIT"}),
        _ => serde_json::json!({"error":"ENGINE_REJECTED"}),
    }
}

#[cfg(all(windows, target_arch = "x86_64"))]
fn error_code<T>(result: std::io::Result<T>) -> serde_json::Value {
    match result {
        Ok(_) => serde_json::json!({"allowed":true}),
        Err(error) => serde_json::json!({"allowed":false,"osError":error.raw_os_error()}),
    }
}

#[cfg(all(windows, target_arch = "x86_64"))]
fn probe(request: &serde_json::Value, inherited_error_mode: u32) -> serde_json::Value {
    use std::fs::OpenOptions;
    match request["operation"].as_str().unwrap_or_default() {
        "read" => error_code(std::fs::read(request["path"].as_str().unwrap())),
        "write" => error_code(
            OpenOptions::new()
                .write(true)
                .open(request["path"].as_str().unwrap())
                .and_then(|mut file| file.write_all(b"ATTEMPTED_WRITE")),
        ),
        "network" | "udp" => network_probe(request),
        "child" => error_code(
            std::process::Command::new(std::env::current_exe().unwrap())
                .arg("--unexpected-child")
                .spawn(),
        ),
        "environment" => serde_json::json!({"variables":std::env::vars().collect::<Vec<_>>() }),
        "error-ui" => {
            use windows_sys::Win32::System::{
                Diagnostics::Debug::GetErrorMode, ErrorReporting::WerGetFlags,
                Threading::GetCurrentProcess,
            };
            let mut flags = 0;
            let result = unsafe { WerGetFlags(GetCurrentProcess(), &mut flags) };
            serde_json::json!({"inheritedErrorMode":inherited_error_mode,"errorMode":unsafe {GetErrorMode()},"werResult":result,"werFlags":flags})
        }
        "crash" => {
            // A deliberately unhandled fixture exception. Exact status and
            // empty Job prove failure stays outside the parent process.
            unsafe {
                windows_sys::Win32::System::Diagnostics::Debug::RaiseException(
                    0xe0422201,
                    0,
                    0,
                    std::ptr::null(),
                );
            }
            serde_json::json!({"error":"CRASH_DID_NOT_TERMINATE"})
        }
        "handle" => {
            let raw = request["handle"].as_u64().unwrap() as usize as *mut std::ffi::c_void;
            let success = unsafe { windows_sys::Win32::System::Threading::SetEvent(raw) } != 0;
            serde_json::json!({"setEventReturned":success,"osError":if success {None} else {std::io::Error::last_os_error().raw_os_error()}})
        }
        "hang" => loop {
            std::hint::spin_loop();
        },
        "output" => {
            let bytes = [b'x'; 4096];
            loop {
                if std::io::stdout().write_all(&bytes).is_err() {
                    std::process::exit(0);
                }
            }
        }
        "memory" => {
            use windows_sys::Win32::System::Memory::{
                VirtualAlloc, VirtualFree, MEM_COMMIT, MEM_RELEASE, MEM_RESERVE, PAGE_READWRITE,
            };
            unsafe {
                let control = VirtualAlloc(
                    std::ptr::null(),
                    65536,
                    MEM_COMMIT | MEM_RESERVE,
                    PAGE_READWRITE,
                );
                if control.is_null() {
                    return serde_json::json!({"control":false});
                }
                VirtualFree(control, 0, MEM_RELEASE);
                let allocation = VirtualAlloc(
                    std::ptr::null(),
                    256 * 1024 * 1024,
                    MEM_COMMIT | MEM_RESERVE,
                    PAGE_READWRITE,
                );
                if allocation.is_null() {
                    serde_json::json!({"control":true,"allowed":false,"osError":std::io::Error::last_os_error().raw_os_error()})
                } else {
                    VirtualFree(allocation, 0, MEM_RELEASE);
                    serde_json::json!({"control":true,"allowed":true})
                }
            }
        }
        _ => serde_json::json!({"error":"PROBE_INVALID"}),
    }
}

#[cfg(all(windows, target_arch = "x86_64"))]
fn network_probe(request: &serde_json::Value) -> serde_json::Value {
    use windows_sys::Win32::Networking::WinSock::*;
    unsafe {
        let mut startup: WSADATA = std::mem::zeroed();
        // std::net panics if its process-wide Winsock initialization is denied.
        // The native fixture reports the real WSAStartup refusal instead.
        let start = WSAStartup(0x202, &mut startup);
        if start != 0 {
            return serde_json::json!({"allowed":false,"osError":start,"stage":"WSAStartup"});
        }
        let udp = request["operation"] == "udp";
        let socket = socket(
            AF_INET as i32,
            if udp { SOCK_DGRAM } else { SOCK_STREAM },
            0,
        );
        if socket == INVALID_SOCKET {
            let code = WSAGetLastError();
            WSACleanup();
            return serde_json::json!({"allowed":false,"osError":code,"stage":"socket"});
        }
        let address: std::net::SocketAddrV4 = request["address"].as_str().unwrap().parse().unwrap();
        let target = SOCKADDR_IN {
            sin_family: AF_INET,
            sin_port: address.port().to_be(),
            sin_addr: IN_ADDR {
                S_un: IN_ADDR_0 {
                    S_addr: u32::from_ne_bytes(address.ip().octets()),
                },
            },
            sin_zero: [0; 8],
        };
        let result = if udp {
            sendto(
                socket,
                b"p22-denied".as_ptr(),
                10,
                0,
                (&target as *const SOCKADDR_IN).cast(),
                std::mem::size_of::<SOCKADDR_IN>() as i32,
            )
        } else {
            connect(
                socket,
                (&target as *const SOCKADDR_IN).cast(),
                std::mem::size_of::<SOCKADDR_IN>() as i32,
            )
        };
        let code = WSAGetLastError();
        closesocket(socket);
        WSACleanup();
        serde_json::json!({"allowed":result != SOCKET_ERROR,"osError":if result == SOCKET_ERROR {Some(code)} else {None},"stage":if udp {"sendto"} else {"connect"}})
    }
}
